def export():
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    path = OUT_DIR / "מילון נתונים - MVP.xlsx"
    with pd.ExcelWriter(path, engine="openpyxl") as xw:
        pd.DataFrame([("גרסה", VERSION),
                      ("מה זה", "הגדרת הדאטה סט של מסגרות לידה-3 ברשות — שלב 1 (MVP), ללא הנגשה"),
                      ("תוצר", "קובץ מסגרות לכל רשות + השוואה מול מיפוי ידני (תיקיית data/output בריפו)"),
                      ("הרצה", "source .env && python3 -m mvp.evaluate")],
                     columns=["", ""]).to_excel(xw, sheet_name="קרא אותי", index=False)
        pd.DataFrame(FIELDS, columns=["שדה", "תיאור", "סוג", "ערכים / פורמט", "מקור", "חובה", "הערות"]) \
            .to_excel(xw, sheet_name="שדות", index=False)
        pd.DataFrame(OUT_OF_SCOPE, columns=["שדה", "למה לא ב-MVP"]).to_excel(xw, sheet_name="מחוץ ל-MVP", index=False)
        pd.DataFrame(SOURCES, columns=["מקור", "סוג", "גישה", "מה מכסה", "עדכניות", "סטטוס", "הערות"]) \
            .to_excel(xw, sheet_name="מקורות", index=False)
        pd.DataFrame(OPEN_QUESTIONS, columns=["#", "שאלה", "מצב נוכחי", "מה צריך להחליט", "מי"]) \
            .to_excel(xw, sheet_name="שאלות פתוחות", index=False)
        pd.DataFrame(MORE_SOURCES, columns=["מקור", "מה ייתן", "חוקיות / סיכון", "המלצה"]) \
            .to_excel(xw, sheet_name="מקורות נוספים ללא מפוקחות", index=False)
        for ws in xw.book.worksheets:
            ws.sheet_view.rightToLeft = True
            for col in ws.columns:
                ws.column_dimensions[col[0].column_letter].width = 28
            for row in ws.iter_rows():
                for c in row:
                    c.alignment = Alignment(wrap_text=True, vertical="top")
    return path


if __name__ == "__main__":
    print(export())
